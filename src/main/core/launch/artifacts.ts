import path from 'node:path'
import type { CrashHint } from '@shared/launch'
import { nodeFsPort, type FsPort } from '../ports'
import type { LaunchAccount, LaunchPlanCore } from './args'

export interface LaunchArtifactsInput {
  dataRoot: string
  plan: LaunchPlanCore
  account: LaunchAccount
  mainClass: string | null
  instanceId: string
  versionName: string
  loader: { type: string; version: string | null }
  javaVersion: string | null
  memory: { minMb: number; maxMb: number }
  codePage: number
  dryRun: boolean
  fs?: FsPort
  now?: () => number
  /** Exact tokens that must never be written (access tokens). */
  secrets?: string[]
}

export interface LaunchArtifactFiles {
  dryRunFile: string | null
  launchLastJson: string
  launchLastBat: string
}

function pad(value: number, length = 2): string {
  return String(value).padStart(length, '0')
}

/** Local time, e.g. 20261021-133015 (log file names are human-scanned). */
export function formatLocalStamp(date: Date): string {
  return (
    `${date.getFullYear()}${pad(date.getMonth() + 1)}${pad(date.getDate())}-` +
    `${pad(date.getHours())}${pad(date.getMinutes())}${pad(date.getSeconds())}`
  )
}

export function gameLogDirectory(dataRoot: string, instanceDirName: string): string {
  return path.join(dataRoot, 'logs', 'game', instanceDirName)
}

/**
 * `$DATA\logs\game\<instance>\<yyyyMMdd-HHmmss>.log` (docs/01 R5.2). A suffix is
 * added when two launches start in the same second.
 */
export function allocateGameLogFile(
  fs: FsPort,
  dataRoot: string,
  instanceDirName: string,
  now: () => number = Date.now,
): string {
  const dir = gameLogDirectory(dataRoot, instanceDirName)
  fs.mkdirp(dir)
  const stamp = formatLocalStamp(new Date(now()))
  let candidate = path.join(dir, `${stamp}.log`)
  let suffix = 2
  while (fs.exists(candidate) && suffix < 100) {
    candidate = path.join(dir, `${stamp}-${suffix}.log`)
    suffix += 1
  }
  return candidate
}

const SAFE_ENV_KEYS = [
  'PATH',
  'Path',
  'PATHEXT',
  'SystemRoot',
  'windir',
  'APPDATA',
  'LOCALAPPDATA',
  'USERPROFILE',
  'TEMP',
  'TMP',
  'PROCESSOR_ARCHITECTURE',
  'OS',
] as const

/**
 * `launch-last.json` is copied into bug reports. Writing the whole environment
 * would leak unrelated API keys/cookies, so only path/shell variables survive.
 */
function safeEnvironment(env: Record<string, string>): Record<string, string> {
  const safe: Record<string, string> = {}
  for (const key of SAFE_ENV_KEYS) {
    if (key in env) safe[key] = env[key]
  }
  return safe
}

function redact(value: string, secrets: string[]): string {
  if (value.length === 0) return value
  // The offline placeholder token `0` is not a secret and must stay readable
  // for the launch-last.bat acceptance check (docs/01 A1.7).
  const active = secrets.filter((secret) => secret && secret !== '0')
  return active.includes(value) ? '<redacted>' : value
}

function redactedArgv(argv: string[], secrets: string[]): string[] {
  return argv.map((token) => redact(token, secrets))
}

function quoteBatArgument(argument: string): string {
  let value = argument.replaceAll('%', '%%')
  if (value.length === 0) return '""'
  if (!/[\s"&|<>^()!]/.test(value)) return value
  value = value.replaceAll('"', '""')
  return `"${value}"`
}

function batContents(input: LaunchArtifactsInput, argv: string[], tokenRedacted: boolean): string {
  const lines = [
    '@echo off',
    `chcp ${input.codePage} >nul`,
    `cd /d "${input.plan.cwd.replaceAll('%', '%%')}"`,
    `REM generated by mc-launcher session ${input.plan.sessionId}`,
  ]
  if (tokenRedacted) {
    lines.push('REM access token redacted; use the launcher to start this instance')
  }
  lines.push(
    [
      `"${input.plan.javaPath.replaceAll('%', '%%').replaceAll('"', '""')}"`,
      ...argv.map(quoteBatArgument),
    ].join(' '),
  )
  return `${lines.join('\r\n')}\r\n`
}

function payload(
  input: LaunchArtifactsInput,
  argv: string[],
): Record<string, unknown> {
  return {
    schemaVersion: 1,
    sessionId: input.plan.sessionId,
    dryRun: input.dryRun,
    createdAt: new Date(input.plan.createdAt).toISOString(),
    instanceId: input.instanceId,
    version: {
      id: input.plan.versionId,
      name: input.versionName,
      mcVersion: input.plan.mcVersion,
      loader: input.loader,
      mainClass: input.mainClass,
    },
    java: {
      path: input.plan.javaPath,
      major: input.plan.javaMajor,
      version: input.javaVersion,
    },
    account: {
      // name/uuid are intentionally present for acceptance evidence; the
      // access token is never written.
      name: input.account.name,
      uuid: input.account.uuid,
      kind: input.account.kind,
      userType: input.account.userType,
    },
    memory: input.memory,
    codePage: input.codePage,
    cwd: input.plan.cwd,
    nativesDir: input.plan.nativesDir,
    classpath: input.plan.classpath,
    argv,
    env: safeEnvironment(input.plan.env),
    warnings: input.plan.warnings,
    exit: null,
  }
}

export interface WriteArtifactsResult extends LaunchArtifactFiles {}

/**
 * Writes `launch-last.json`, `launch-last.bat` and (for dry runs)
 * `dry-run.json`. `dry-run.json` is the acceptance artifact for P0-2/3/4/7/8;
 * no process is started by the caller.
 */
export function writeLaunchArtifacts(input: LaunchArtifactsInput): WriteArtifactsResult {
  const fs = input.fs ?? nodeFsPort()
  const secrets = input.secrets ?? []
  const logsDir = path.join(input.dataRoot, 'logs')
  fs.mkdirp(logsDir)

  const argv = redactedArgv(input.plan.argv, secrets)
  const tokenRedacted = input.plan.argv.some((token, index) => token !== argv[index])
  const body = payload(input, argv)

  const launchLastJson = path.join(logsDir, 'launch-last.json')
  const launchLastBat = path.join(logsDir, 'launch-last.bat')
  fs.writeTextAtomic(launchLastJson, `${JSON.stringify(body, null, 2)}\n`)
  fs.writeTextAtomic(launchLastBat, batContents(input, argv, tokenRedacted))

  let dryRunFile: string | null = null
  if (input.dryRun) {
    dryRunFile = path.join(logsDir, 'dry-run.json')
    fs.writeTextAtomic(
      dryRunFile,
      `${JSON.stringify({ ...body, dryRun: true }, null, 2)}\n`,
    )
  }

  return { dryRunFile, launchLastJson, launchLastBat }
}

export interface LaunchExitSummary {
  exitCode: number | null
  signal: string | null
  durationMs: number
  classification: string
  crashHints: CrashHint[]
  logFile: string
  sawMenu: boolean
}

/** Appends exit evidence to launch-last.json (R5.10). */
export function updateLaunchLastExit(
  dataRoot: string,
  summary: LaunchExitSummary,
  fs: FsPort = nodeFsPort(),
): string | null {
  const file = path.join(dataRoot, 'logs', 'launch-last.json')
  if (!fs.exists(file)) return null
  try {
    const parsed = JSON.parse(fs.readText(file)) as Record<string, unknown>
    parsed.exit = {
      exitCode: summary.exitCode,
      signal: summary.signal,
      durationMs: summary.durationMs,
      classification: summary.classification,
      sawMenu: summary.sawMenu,
      logFile: summary.logFile,
      crashHints: summary.crashHints,
      at: new Date().toISOString(),
    }
    fs.writeTextAtomic(file, `${JSON.stringify(parsed, null, 2)}\n`)
    return file
  } catch {
    return null
  }
}
